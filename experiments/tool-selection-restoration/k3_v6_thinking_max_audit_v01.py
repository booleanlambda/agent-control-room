#!/usr/bin/env python3
"""Audit actual Kimi UCCR tool calls and frozen selection without model self-grade."""
import hashlib,json,sys
from pathlib import Path
from v5_independent_structure_gate import validate
HERE=Path(__file__).resolve().parent
E=HERE/"evidence_k3_on_v6_parallel_max_v01"
def sha(b):return hashlib.sha256(b).hexdigest()
def audit():
 result_path=E/"summary.json"
 if not result_path.exists():
  print("K3_V6_THINKING_MAX_AUDIT=NO_RECEIPT")
  return 1
 receipt=json.loads(result_path.read_text())
 manifest=json.loads((HERE/"external_tool_proof_obligations_v1.json").read_text())
 catalog=json.loads((HERE/"aau_registry_db_export_v01.json").read_text())
 if receipt.get("proposal") is None:
  result={"result":"NO_COMPLETE_TOOLCHAIN_RESPONSE","provider_status":receipt.get("status")}
 else:
  result=validate(receipt["proposal"],manifest)
  raw=json.dumps(receipt["proposal"],ensure_ascii=False)
  cited=[o["operation_id"] for o in catalog["operations"] if o["operation_id"] in raw]
  result["proposal_summary"]={
   "tool_names":[t.get("name") for t in receipt["proposal"].get("selected_tools",[]) if isinstance(t,dict)],
   "required_computations_count":len(receipt["proposal"].get("required_computations",[])),
   "independent_tests_count":len(receipt["proposal"].get("independent_verification_tests",[])),
   "interfaces_count":len(receipt["proposal"].get("interface_contracts",[])),
   "known_invalid_networkx_has_cycle_invocation":'nx.has_cycle(' in raw,
   "explicit_registry_operation_id_citations":cited,
   "self_assessment":receipt["proposal"].get("stage1_assessment",{}),
  }
  result["catalog_status"]={
    "data_source":"read-only local JSON export generated by SQL from live private Supabase registry",
    "export_sha256":receipt["frozen"]["aau_registry_db_export_v01.json"]["sha256"],
    "live_database_query_during_provider_run":False,
    "narrow_operations_count":len(catalog["operations"]),
    "all_references_scope_limited":True
  }
 result["tool_use"]={
    "registered_names":["search_capabilities","inspect_operation"],
    "call_count":len(receipt.get("tool_invocations",[])),
    "calls_by_name":{name:sum(t["name"]==name for t in receipt["tool_invocations"])
                     for name in ["search_capabilities","inspect_operation"]},
    "errors":[x for x in receipt.get("tool_invocations",[])
              if isinstance(x.get("output"),dict) and x["output"].get("error")],
    "tool_calls_are_provider_generated":True,
    "live_parallel_discovery_count":len([x for x in receipt.get("tool_invocations",[]) if x.get("name")=="parallel_software_discovery"]),
    "parallel_search_source_urls":sorted(set(r.get("url") for c in receipt.get("tool_invocations",[]) if c.get("name")=="parallel_software_discovery" for r in c.get("output",{}).get("results",[]) if isinstance(r,dict) and r.get("url"))),
    "thinking_on_verified":receipt.get("thinking_on_verified",False),
    "observed_reasoning_characters":sum(int(a.get("reasoning_chars") or 0) for a in receipt.get("attempts",[]))
 }
 if receipt.get("first_provider_turn_requires_parallel_call") and not any(
   t.get("name")=="parallel_software_discovery" and t.get("turn")==1
   for t in receipt.get("tool_invocations",[])):
  result["result"]="FIRST_TURN_PARALLEL_CALL_MISSING"
 elif not result["tool_use"]["live_parallel_discovery_count"]:
  result["result"]="NO_LIVE_PARALLEL_DISCOVERY_CALL"
 elif receipt.get("thinking_on_verified") is not True:
  result["result"]="K3_THINKING_MAX_NOT_OBSERVED"
 elif receipt.get("status")!="PROPOSAL_PENDING_EXTERNAL_VERIFICATION":
  result["result"]="NO_VALID_COMPLETE_TOOL_AUGMENTED_PROPOSAL"
 elif not result["tool_use"]["call_count"]:
  result["result"]="NO_REGISTRY_TOOL_USE"
 # Deterministic regression diagnostics, known independently verified defects
 # from the preceding V5 proposal. These are checks, NOT a second LLM call,
 # and do not claim complete mathematical/safety proof.
 p=receipt.get("proposal") or {}
 tooltext=" ".join(str(t.get("installation_command",""))+" "+str(t.get("concrete_executable_operation","")) for t in p.get("selected_tools",[]) if isinstance(t,dict)).lower()
 packages=" ".join(str(t.get("installation_command","")) for t in p.get("selected_tools",[]) if isinstance(t,dict)).lower()
 ints=[i for i in p.get("interface_contracts",[]) if isinstance(i,dict)]
 iftext=" ".join(str(i.get("conversion",""))+" "+str(i.get("fields_with_types_and_units",""))+" "+str(i.get("invalid_data_rejection","")) for i in ints).lower()
 results={}
 results["bad_pysp_pin_present"]="pysp==6.0.0" in packages or "pip install pysp" in packages
 results["unsafe_nearest_hour_present"]="rounded to nearest hour" in iftext or "round to nearest hour" in iftext
 results["opendssdirect_import_without_package"]=("opendssdirect" in tooltext and "opendssdirect.py" not in packages and "dss-python" in packages)
 results["unqualified_osrm_container_only"]=any(
  "osrm" in str(t.get("name","")).lower() and
  ("docker run osrm/osrm-backend" in str(t.get("installation_command","")).lower()) and
  "osrm-extract" not in str(t.get("installation_command","")).lower()
  for t in p.get("selected_tools",[]) if isinstance(t,dict))
 results["commercial_tools_claimed_executed"]=any(
  str(t.get("execution_status","")).upper() in ("PASS","VERIFIED_EXECUTED")
  for t in p.get("installation_and_test_commands",[]) if isinstance(t,dict) and
  any(x in str(t.get("tool_id","")).lower() for x in ["etap","pscad","emtp","cyme"]))
 results["opendss_etap_insufficient_handoff"]=any(
  "opendss" in str(i.get("from_tool_id","")).lower() and
  ("etap" in str(i.get("to_tool_id","")).lower() or "cyme" in str(i.get("to_tool_id","")).lower()) and
  not any(key in str(i.get("fields_with_types_and_units","")).lower() for key in ["relay","impedance","topology","fault","protection"])
  for i in ints)
 result["regression_diagnostics"]=results
 result["known_prior_defect_patterns"]=sum(1 for x in results.values() if x)
 result["missing_domain_assessment"]="STRUCTURAL ONLY, NO AUTOMATIC SPECIALIST SUITABILITY/EXECUTION PASS"
 result["stage2_authorized"]=False
 result["frozen_original_grader_score"]=None
 (E/"independent_uccr_verdict.json").write_text(json.dumps(result,indent=2,ensure_ascii=False)+"\n")
 print("UCCR_THINKING_MAX_AUDIT="+json.dumps({
    "result":result["result"],"structural_error_count":len(result.get("structural_errors",[])),
    "structural_errors":result.get("structural_errors",[])[:20],
    "tool_calls":result["tool_use"]["call_count"],
    "thinking_on_verified":result["tool_use"]["thinking_on_verified"],
    "observed_reasoning_characters":result["tool_use"]["observed_reasoning_characters"],
    "catalog_citations":(result.get("proposal_summary") or {}).get("explicit_registry_operation_id_citations",[]),
    "selected_tools":(result.get("proposal_summary") or {}).get("tool_names",[]),
    "known_prior_defect_patterns":result.get("known_prior_defect_patterns"),
    "regression_diagnostics":result.get("regression_diagnostics"),
    "stage2_authorized":False
   }),flush=True)
 return 0
if __name__=="__main__":sys.exit(audit())
