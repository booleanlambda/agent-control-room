#!/usr/bin/env python3
"""Audit actual Kimi UCCR tool calls and frozen selection without model self-grade."""
import hashlib,json,sys
from pathlib import Path
from v5_independent_structure_gate import validate
HERE=Path(__file__).resolve().parent
E=HERE/"evidence_readonly_tools_v01"
def sha(b):return hashlib.sha256(b).hexdigest()
def audit():
 result_path=E/"summary.json"
 if not result_path.exists():
  print("UCCR_EXTERNAL_AUDIT=NO_RECEIPT")
  return 1
 receipt=json.loads(result_path.read_text())
 manifest=json.loads((HERE/"external_tool_proof_obligations_v1.json").read_text())
 catalog=json.loads((HERE/"aau_registry_db_export_v01.json").read_text())
 if receipt.get("proposal") is None:
  result={"result":"NO_COMPLETE_TOOLCHAIN_RESPONSE","provider_status":receipt.get("status")}
 else:
  result=validate(receipt["proposal"],manifest)
  raw=json.dumps(receipt["proposal"],ensure_ascii=False)
  cited=[o["operation_id"] for o in catalog["operations"] if o["operation_id"] in raw]
  result["proposal_summary"]={
   "tool_names":[t.get("name") for t in receipt["proposal"].get("selected_tools",[]) if isinstance(t,dict)],
   "required_computations_count":len(receipt["proposal"].get("required_computations",[])),
   "independent_tests_count":len(receipt["proposal"].get("independent_verification_tests",[])),
   "interfaces_count":len(receipt["proposal"].get("interface_contracts",[])),
   "known_invalid_networkx_has_cycle_invocation":'nx.has_cycle(' in raw,
   "explicit_registry_operation_id_citations":cited,
   "self_assessment":receipt["proposal"].get("stage1_assessment",{}),
  }
  result["catalog_status"]={
    "data_source":"read-only local JSON export generated by SQL from live private Supabase registry",
    "export_sha256":receipt["frozen"]["aau_registry_db_export_v01.json"]["sha256"],
    "live_database_query_during_provider_run":False,
    "narrow_operations_count":len(catalog["operations"]),
    "all_references_scope_limited":True
  }
 result["tool_use"]={
    "registered_names":["search_capabilities","inspect_operation"],
    "call_count":len(receipt.get("tool_invocations",[])),
    "calls_by_name":{name:sum(t["name"]==name for t in receipt["tool_invocations"])
                     for name in ["search_capabilities","inspect_operation"]},
    "errors":[x for x in receipt.get("tool_invocations",[])
              if isinstance(x.get("output"),dict) and x["output"].get("error")],
    "tool_calls_are_provider_generated":True
 }
 if receipt.get("status")!="PROPOSAL_PENDING_EXTERNAL_VERIFICATION":
  result["result"]="NO_VALID_COMPLETE_TOOL_AUGMENTED_PROPOSAL"
 elif not result["tool_use"]["call_count"]:
  result["result"]="NO_REGISTRY_TOOL_USE"
 result["missing_domain_assessment"]="NOT_INFERRED_FROM_STRUCTURAL_PASS; REQUIRES_INDEPENDENT SPECIALIST REVIEW"
 result["stage2_authorized"]=False
 result["frozen_original_grader_score"]=None
 (E/"independent_uccr_verdict.json").write_text(json.dumps(result,indent=2,ensure_ascii=False)+"\n")
 print("UCCR_EXTERNAL_AUDIT="+json.dumps({
    "result":result["result"],"structural_error_count":len(result.get("structural_errors",[])),
    "structural_errors":result.get("structural_errors",[])[:20],
    "tool_calls":result["tool_use"]["call_count"],
    "catalog_citations":(result.get("proposal_summary") or {}).get("explicit_registry_operation_id_citations",[]),
    "selected_tools":(result.get("proposal_summary") or {}).get("tool_names",[]),
    "stage2_authorized":False
   }),flush=True)
 return 0
if __name__=="__main__":sys.exit(audit())
